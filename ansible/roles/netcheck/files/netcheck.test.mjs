import assert from 'node:assert/strict';
import { test } from 'node:test';
import { changes, defaultRoute, grade, nameservers } from './netcheck.mjs';

test('quick is ok, a second or more is slow, and a failure fails', () => {
	assert.equal(grade(true, 40), 'ok');
	assert.equal(grade(true, 1000), 'slow');
	assert.equal(grade(false, 5), 'fail');
});

test('the nameservers come from resolv.conf, in order', () => {
	const conf = '# Generated by NetworkManager\nsearch Home\nnameserver 192.168.0.1\nnameserver fd31:4f25::6\n';
	assert.deepEqual(nameservers(conf), ['192.168.0.1', 'fd31:4f25::6']);
	assert.deepEqual(nameservers(''), []);
});

test('the default route is read from ip -j', () => {
	const json = '[{"dst":"default","gateway":"192.168.0.1","dev":"eth0","protocol":"dhcp","metric":100}]';
	assert.deepEqual(defaultRoute(json), { dev: 'eth0', gateway: '192.168.0.1' });
	assert.equal(defaultRoute('[]'), null);
	assert.equal(defaultRoute(''), null);
});

test('the first round logs every state', () => {
	const since = {};
	const lines = changes(null, { router: { state: 'ok' }, 'dns 192.168.0.1': { state: 'ok' } }, since, 1000);
	assert.deepEqual(lines, ['router: ok', 'dns 192.168.0.1: ok']);
	assert.deepEqual(since, { router: 1000, 'dns 192.168.0.1': 1000 });
});

test('nothing is logged while nothing changes', () => {
	const since = { router: 0 };
	assert.deepEqual(changes({ router: { state: 'ok' } }, { router: { state: 'ok' } }, since, 5000), []);
	assert.deepEqual(since, { router: 0 });
});

test('a change is logged with its detail, and a recovery with how long the spell lasted', () => {
	const since = { 'dns 192.168.0.1': 0 };
	const ok = { state: 'ok' };
	const failed = { state: 'fail', detail: 'ETIMEOUT' };
	assert.deepEqual(changes({ 'dns 192.168.0.1': ok }, { 'dns 192.168.0.1': failed }, since, 60_000), [
		'dns 192.168.0.1: ok → fail after 60 s (ETIMEOUT)'
	]);
	assert.deepEqual(changes({ 'dns 192.168.0.1': failed }, { 'dns 192.168.0.1': ok }, since, 78_000), [
		'dns 192.168.0.1: fail → ok after 18 s'
	]);
});

test('a slow answer is a change of its own', () => {
	const since = { 'internet 1.1.1.1': 0 };
	assert.deepEqual(
		changes(
			{ 'internet 1.1.1.1': { state: 'ok' } },
			{ 'internet 1.1.1.1': { state: 'slow', detail: '2400 ms' } },
			since,
			10_000
		),
		['internet 1.1.1.1: ok → slow after 10 s (2400 ms)']
	);
});

test('a nameserver that disappears from resolv.conf is logged as gone', () => {
	const since = { 'dns fd31::6': 0 };
	assert.deepEqual(changes({ 'dns fd31::6': { state: 'ok' } }, {}, since, 1000), ['dns fd31::6: gone']);
	assert.deepEqual(since, {});
});
